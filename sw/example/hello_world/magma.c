/*
 * Magma (GOST R 34.12-2015) — Bitmanip demonstration.
 *
 * Two implementations to show Bitmanip benefit:
 *
 * [A] magma_encrypt_prerot  — PRE-ROTATED tables (ROL11 absorbed at compile time)
 *     Tables hold S(x) already rotated left by 11 bits.  No rori in hot path.
 *     Zbb gives ZERO benefit here. Serves as baseline vs [B].
 *
 * [B] magma_encrypt_rori    — NATURAL tables + explicit ROL11 each round
 *     Tables hold S(x) in natural bit positions.  ROL11 applied after OR.
 *     GCC + Zbb emits:  rori rd, rs, 21   (1 instruction = ROL11)
 *     Without Zbb:      srli + slli + or  (~48 cycles)
 *     32 rounds × 1 rori = savings: 32 * (48-22) = 832 cycles/block.
 *
 * Zbkb rev8 (load_be32): lw + rev8 = 2 instr vs 7 instr per word.
 * Used 2x per block => ~50-100 cycles additional savings.
 *
 * All tables are const → .rodata (IMEM) → zero DMEM/BSS usage.
 * 8 tables × 1 KB = 8 KB in IMEM.
 */

