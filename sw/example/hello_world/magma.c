/* -----------------------------------------------------------------------
 * BIG-ENDIAN 32-BIT LOAD / STORE
 * With Zbkb: lw + rev8  (2 instructions)
 * Without:   4 shifts + 3 ORs  (7 instructions)
 * ---------------------------------------------------------------------- */
static inline uint32_t load_be32(const uint8_t *p)
{
    uint32_t v;
    memcpy(&v, p, 4);
#ifdef __riscv_zbkb
    __asm__ volatile("rev8 %0,%0" : "+r"(v));
#else
    v = ((v & 0x000000ffu) << 24) | ((v & 0x0000ff00u) <<  8) |
        ((v & 0x00ff0000u) >>  8) | ((v & 0xff000000u) >> 24);
#endif
    return v;
}

static inline void store_be32(uint8_t *p, uint32_t v)
{
#ifdef __riscv_zbkb
    __asm__ volatile("rev8 %0,%0" : "+r"(v));
#else
    v = ((v & 0x000000ffu) << 24) | ((v & 0x0000ff00u) <<  8) |
        ((v & 0x00ff0000u) >>  8) | ((v & 0xff000000u) >> 24);
#endif
    memcpy(p, &v, 4);
}

