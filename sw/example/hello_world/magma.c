/* -----------------------------------------------------------------------
 * Key setup: load big-endian 32-bit subkeys.
 * ---------------------------------------------------------------------- */
void magma_init(magma_ctx_t *ctx, const uint8_t key[32])
{
    for (int i = 0; i < 8; i++)
        ctx->k[i] = load_be32(key + 4 * i);
}

/* -----------------------------------------------------------------------
 * [A] PRE-ROTATED f(x): tables absorb ROL11 — no rori emitted.
 * ---------------------------------------------------------------------- */
static inline uint32_t f_prerot(uint32_t x)
{
    return prerot87[ x >> 24        ]
         | prerot65[(x >> 16) & 0xff]
         | prerot43[(x >>  8) & 0xff]
         | prerot21[ x        & 0xff];
}

void magma_encrypt_prerot(const magma_ctx_t *ctx,
                          const uint8_t in[8], uint8_t out[8])
{
    uint32_t n1 = load_be32(in + 4);
    uint32_t n2 = load_be32(in);
#define R_P(a,b,ki)  (a) ^= f_prerot((b) + ctx->k[ki])
    R_P(n2,n1,0); R_P(n1,n2,1); R_P(n2,n1,2); R_P(n1,n2,3);
    R_P(n2,n1,4); R_P(n1,n2,5); R_P(n2,n1,6); R_P(n1,n2,7);
    R_P(n2,n1,0); R_P(n1,n2,1); R_P(n2,n1,2); R_P(n1,n2,3);
    R_P(n2,n1,4); R_P(n1,n2,5); R_P(n2,n1,6); R_P(n1,n2,7);
    R_P(n2,n1,0); R_P(n1,n2,1); R_P(n2,n1,2); R_P(n1,n2,3);
    R_P(n2,n1,4); R_P(n1,n2,5); R_P(n2,n1,6); R_P(n1,n2,7);
    R_P(n2,n1,7); R_P(n1,n2,6); R_P(n2,n1,5); R_P(n1,n2,4);
    R_P(n2,n1,3); R_P(n1,n2,2); R_P(n2,n1,1); R_P(n1,n2,0);
#undef R_P
    store_be32(out,     n1);
    store_be32(out + 4, n2);
}

void magma_decrypt_prerot(const magma_ctx_t *ctx,
                          const uint8_t in[8], uint8_t out[8])
{
    uint32_t n1 = load_be32(in + 4);
    uint32_t n2 = load_be32(in);
#define R_P(a,b,ki)  (a) ^= f_prerot((b) + ctx->k[ki])
    R_P(n2,n1,0); R_P(n1,n2,1); R_P(n2,n1,2); R_P(n1,n2,3);
    R_P(n2,n1,4); R_P(n1,n2,5); R_P(n2,n1,6); R_P(n1,n2,7);
    R_P(n2,n1,7); R_P(n1,n2,6); R_P(n2,n1,5); R_P(n1,n2,4);
    R_P(n2,n1,3); R_P(n1,n2,2); R_P(n2,n1,1); R_P(n1,n2,0);
    R_P(n2,n1,7); R_P(n1,n2,6); R_P(n2,n1,5); R_P(n1,n2,4);
    R_P(n2,n1,3); R_P(n1,n2,2); R_P(n2,n1,1); R_P(n1,n2,0);
    R_P(n2,n1,7); R_P(n1,n2,6); R_P(n2,n1,5); R_P(n1,n2,4);
    R_P(n2,n1,3); R_P(n1,n2,2); R_P(n2,n1,1); R_P(n1,n2,0);
#undef R_P
    store_be32(out,     n1);
    store_be32(out + 4, n2);
}

/* -----------------------------------------------------------------------
 * [B] NATURAL + explicit ROL11:
 * GCC+Zbb: (s<<11)|(s>>21)  →  rori rd, rs, 21   (1 instruction)
 * Without: srli + slli + or  ≈ 48 cycles(stalls)
 * ---------------------------------------------------------------------- */
static inline uint32_t f_natural(uint32_t x)
{
    uint32_t s = nat87[ x >> 24        ]
               | nat65[(x >> 16) & 0xff]
               | nat43[(x >>  8) & 0xff]
               | nat21[ x        & 0xff];
    return (s << 11) | (s >> 21);   /* ROL11  →  rori rd,rs,21  with Zbb */
}

void magma_encrypt_rori(const magma_ctx_t *ctx,
                        const uint8_t in[8], uint8_t out[8])
{
    uint32_t n1 = load_be32(in + 4);
    uint32_t n2 = load_be32(in);
#define R_N(a,b,ki)  (a) ^= f_natural((b) + ctx->k[ki])
    R_N(n2,n1,0); R_N(n1,n2,1); R_N(n2,n1,2); R_N(n1,n2,3);
    R_N(n2,n1,4); R_N(n1,n2,5); R_N(n2,n1,6); R_N(n1,n2,7);
    R_N(n2,n1,0); R_N(n1,n2,1); R_N(n2,n1,2); R_N(n1,n2,3);
    R_N(n2,n1,4); R_N(n1,n2,5); R_N(n2,n1,6); R_N(n1,n2,7);
    R_N(n2,n1,0); R_N(n1,n2,1); R_N(n2,n1,2); R_N(n1,n2,3);
    R_N(n2,n1,4); R_N(n1,n2,5); R_N(n2,n1,6); R_N(n1,n2,7);
    R_N(n2,n1,7); R_N(n1,n2,6); R_N(n2,n1,5); R_N(n1,n2,4);
    R_N(n2,n1,3); R_N(n1,n2,2); R_N(n2,n1,1); R_N(n1,n2,0);
#undef R_N
    store_be32(out,     n1);
    store_be32(out + 4, n2);
}

