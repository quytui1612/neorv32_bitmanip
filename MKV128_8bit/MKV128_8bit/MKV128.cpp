void setInitialKeyState128(int r, u8* K, u8* Block1, u8* Block2) {
	int i;
	copyState(Block1, K, 16);
	if (r == Round128) {
		for (i = 0; i < 16; i++) Block2[i] = K[i] ^ 0xFF;  //Nua con lai lay phu dinh
	}
	if (r == Round192) {
		copyState(Block2, K + 16, 8);
		for (i = 8; i < 16; i++) Block2[i] = K[i] ^ 0xFF;
	}
	if (r == Round256) {
		copyState(Block2, K + 16, 16);
	}
}
