void XWords(u8* X, u8* Y) {
	for (int i = 0; i < BlockLength; i++)
		Y[i] = X[(i + 4) % BlockLength] ^ X[(i + 8) % BlockLength] ^ X[(i + 12) % BlockLength];
}
void AddRoundKey(u8* X, u8* Y, u8* Key) {
	for (int i = 0; i < BlockLength; i++) Y[i] = X[i] ^ Key[i];
}

