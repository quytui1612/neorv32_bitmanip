void matrmultcol1(u8* X, u8 A[n][n], u8* Y, int k) {
	int i, j;
	for (i = 0; i < n; i++) Y[i] = 0;
	for (i = 0; i < n; i++) {
		for (j = 0; j < n - k; j++)
			Y[i] ^= Mult[X[j + k]][A[i][j]];
		for (j = 0; j < k; j++)
			Y[i] ^= Mult[X[j]][A[i][n - k + j]];
	}
}
void matrmultcol2(u8* X, u8 A[n][n], u8* Y, int k) {
	int i, j;
	u8 tmp[n];
	for (i = 0; i < n; i++) {
		Y[i] = 0;
		tmp[i] = 0;
	}
	for (i = 0; i < n; i++) {
		for (j = 0; j < n; j++)
			tmp[i] ^= Mult[X[j]][A[i][j]];
		for (j = 0; j < k; j++) Y[j] = tmp[n - k + j];
		for (j = 0; j < n - k; j++) Y[k + j] = tmp[j];
	}
}

